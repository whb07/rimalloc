#!/usr/bin/env python3
"""Generate or verify the advisory unsafe source inventory."""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess


ROOT = pathlib.Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs/unsafe-inventory.md"

BUILD_MODES = [
    ("normal", "default features", "cargo check"),
    ("c-abi", "c-abi", "cargo check --features c-abi"),
    ("interpose", "interpose", "cargo check --features interpose"),
    ("secure", "secure", "cargo check --features secure"),
    ("guarded", "guarded", "cargo check --features guarded"),
    ("track-valgrind", "track-valgrind", "cargo check --features track-valgrind"),
    ("track-asan", "track-asan", "cargo check --features track-asan"),
]

PATTERNS = [
    ("unsafe_blocks", re.compile(r"\bunsafe\s*\{")),
    (
        "unsafe_fns",
        re.compile(r"\bunsafe\s+(?:extern\s+(?:\"[^\"]+\"\s+)?)?fn\b"),
    ),
    (
        "unsafe_extern_blocks",
        re.compile(r"\bunsafe\s+extern\s+(?:\"[^\"]+\"\s*)?\{"),
    ),
    ("unsafe_impls", re.compile(r"\bunsafe\s+impl\b")),
    ("unsafe_attrs", re.compile(r"#\[\s*unsafe\s*\(")),
    ("global_asm", re.compile(r"\bglobal_asm!\s*\(")),
]


def rust_sources() -> list[pathlib.Path]:
    return sorted((ROOT / "src").rglob("*.rs"))


def file_counts(path: pathlib.Path) -> dict[str, int]:
    text = path.read_text()
    counts = {"unsafe_mentions": len(re.findall(r"\bunsafe\b", text))}
    for name, pattern in PATTERNS:
        counts[name] = len(pattern.findall(text))
    return counts


def inventory() -> list[tuple[str, dict[str, int]]]:
    rows: list[tuple[str, dict[str, int]]] = []
    for path in rust_sources():
        counts = file_counts(path)
        if counts["unsafe_mentions"] > 0:
            rows.append((path.relative_to(ROOT).as_posix(), counts))
    return rows


def totals(rows: list[tuple[str, dict[str, int]]]) -> dict[str, int]:
    result = {name: 0 for name in ["unsafe_mentions", *(name for name, _ in PATTERNS)]}
    for _path, counts in rows:
        for name, count in counts.items():
            result[name] += count
    return result


def build_report() -> str:
    rows = inventory()
    total = totals(rows)
    lines = [
        "# Unsafe Inventory",
        "",
        "Generated by `scripts/check-unsafe-inventory.py --write`.",
        "",
        "This is advisory release evidence, not a substitute for the unsafe audit.",
        "`UNSAFE_AUDIT.md`, `docs/unsafe-audit-evidence.tsv`, Miri, sanitizer,",
        "parity, and focused tests remain the safety proof.",
        "",
        "## Build Modes",
        "",
        "Run `scripts/check-unsafe-inventory.py --verify-builds` before release to",
        "verify the source inventory after each supported advisory build mode checks.",
        "",
        "| Mode | Feature set | Command |",
        "| --- | --- | --- |",
    ]
    for mode, features, command in BUILD_MODES:
        lines.append(f"| `{mode}` | {features} | `{command}` |")

    lines.extend(
        [
            "",
            "## Counts",
            "",
            "| Metric | Count |",
            "| --- | ---: |",
        ]
    )
    for name in ["unsafe_mentions", *(name for name, _ in PATTERNS)]:
        lines.append(f"| `{name}` | {total[name]} |")

    lines.extend(
        [
            "",
            "## Files",
            "",
            "| File | unsafe | blocks | fns | extern blocks | impls | attrs | global asm |",
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
    )
    for path, counts in rows:
        lines.append(
            "| "
            f"`{path}` | "
            f"{counts['unsafe_mentions']} | "
            f"{counts['unsafe_blocks']} | "
            f"{counts['unsafe_fns']} | "
            f"{counts['unsafe_extern_blocks']} | "
            f"{counts['unsafe_impls']} | "
            f"{counts['unsafe_attrs']} | "
            f"{counts['global_asm']} |"
        )

    lines.extend(
        [
            "",
            "## Review Policy",
            "",
            "- Treat count changes as review prompts, not automatic failures of safety.",
            "- For new unsafe operations, add nearby `SAFETY[AUDIT:*]` markers or a",
            "  dated migration allowlist entry, then update the audit evidence mapping.",
            "- Regenerate this report with `scripts/check-unsafe-inventory.py --write`",
            "  only after reviewing the diff and confirming the change is intentional.",
            "- If counts move because code was deleted or made safe, keep the report diff",
            "  with the same change so reviewers can see the reduction.",
            "",
        ]
    )
    return "\n".join(lines)


def verify_build_modes() -> None:
    for mode, _features, command in BUILD_MODES:
        print(f"+ {command}  # unsafe inventory mode: {mode}")
        subprocess.run(command.split(), cwd=ROOT, check=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="rewrite docs/unsafe-inventory.md")
    parser.add_argument(
        "--verify-builds",
        action="store_true",
        help="run cargo check for each advisory inventory build mode",
    )
    args = parser.parse_args()

    if args.verify_builds:
        verify_build_modes()

    expected = build_report()
    if args.write:
        REPORT.write_text(expected)
        print(f"wrote {REPORT.relative_to(ROOT)}")
        return 0

    actual = REPORT.read_text() if REPORT.exists() else ""
    if actual != expected:
        raise AssertionError(
            "unsafe inventory report is out of date; run "
            "scripts/check-unsafe-inventory.py --write"
        )
    print(f"ok: unsafe inventory report covers {len(inventory())} source files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
